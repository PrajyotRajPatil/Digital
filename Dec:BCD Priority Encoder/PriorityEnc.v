module PriorityEnc(
    input [9:0] i,
    output [3:0] y
);
    assign y = (i[9] == 1'b1) ? 4'b1001 :
               (i[8] == 1'b1) ? 4'b1000 :
               (i[7] == 1'b1) ? 4'b0111 :
               (i[6] == 1'b1) ? 4'b0110 :
               (i[5] == 1'b1) ? 4'b0101 :
               (i[4] == 1'b1) ? 4'b0100 :
               (i[3] == 1'b1) ? 4'b0011 :
               (i[2] == 1'b1) ? 4'b0010 :
               (i[1] == 1'b1) ? 4'b0001 :
               (i[0] == 1'b1) ? 4'b0000 :
                                4'b0000; 
endmodule
